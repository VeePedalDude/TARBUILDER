// Song IR -> alphaTex (alphaTab 1.9 syntax), ready for `tarb build` -> Guitar Pro 7.
import { trackLayout } from './notation.mjs';
import { assignFrets } from './fret.mjs';
import { parseKey, spellNameInKey } from '../theory/key.mjs';
import { barStart, assertValid, cloneSong, meterAt } from '../ir.mjs';

const KS_NAMES = { '-7': 'Cb', '-6': 'Gb', '-5': 'Db', '-4': 'Ab', '-3': 'Eb', '-2': 'Bb', '-1': 'F', 0: 'C', 1: 'G', 2: 'D', 3: 'A', 4: 'E', 5: 'B', 6: 'F#', 7: 'C#' };

const q = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

function noteFx(n) {
  const fx = n.fx ?? {};
  const parts = [];
  if (fx.pm) parts.push('pm');
  if (fx.h) parts.push('h');
  if (fx.sl) parts.push('sl');
  if (fx.b) parts.push(`b (${fx.b.join(' ')})`);
  if (fx.v) parts.push('v');
  if (fx.lr) parts.push('lr');
  if (fx.x) parts.push('x');
  if (fx.nh) parts.push('nh');
  if (fx.g) parts.push('g');
  if (fx.ac) parts.push('ac');
  if (fx.st) parts.push('st');
  return parts;
}

/**
 * options: { chordTrack: index of the track that shows chord names (default first non-drum),
 *            fret: { ...FRET_COSTS overrides } }
 */
export function toAlphaTex(songIn, options = {}) {
  const song = cloneSong(songIn);
  assertValid(song);
  const key = parseKey(song.key ?? 'C major');
  const lines = [];
  lines.push(`// Generated by TARBUILDER tools/music`);
  lines.push(`\\title (${q(song.title ?? 'Untitled')})`);
  if (song.artist) lines.push(`\\artist (${q(song.artist)})`);
  lines.push(`\\tempo (${Math.round(song.tempo)})`);
  lines.push('');

  const chordTrack = options.chordTrack ?? song.tracks.findIndex((t) => t.kind !== 'drums');
  const chordStarts = new Map((song.chords ?? []).map((c) => [c.start, c.symbol]));
  const sections = new Map((song.sections ?? []).map((s) => [s.bar, s.name]));
  const tempos = new Map((song.tempoChanges ?? []).map((t) => [t.bar, t.bpm]));
  const meters = new Map((song.meterChanges ?? []).map((m) => [m.bar, m]));

  song.tracks.forEach((track, ti) => {
    if (track.kind === 'fretted') assignFrets(track, options.fret);
    const short = track.name.slice(0, 4);
    lines.push(`\\track (${q(track.name)} ${q(short)}) { instrument ${track.kind === 'drums' ? 'percussion' : track.program} }`);
    if (track.kind === 'fretted') {
      lines.push(`\\staff {tabs score}`);
      lines.push(`\\tuning (${track.tuning.join(' ')})`);
    } else if (track.kind === 'drums') {
      lines.push(`\\staff {score}`);
      lines.push(`\\clef (neutral)`);
    } else {
      lines.push(`\\staff {score}`);
      lines.push(`\\tuning (piano)`);
    }
    const clef = track.clef ?? (track.kind === 'pitched' && avgPitch(track) < 55 ? 'F4' : null);
    if (clef && track.kind !== 'drums') lines.push(`\\clef (${clef})`);
    if (ti === 0) lines.push(`\\ks (${KS_NAMES[Math.max(-7, Math.min(7, key.fifths))]})`);
    lines.push(`\\ts (${song.meter.num} ${song.meter.den})`);

    const layout = trackLayout(song, track, ti === chordTrack ? [...chordStarts.keys()] : []);
    layout.forEach((bars, vi) => {
      let curDen = null;
      if (layout.length > 1) lines.push('\\voice');
      bars.forEach((items, b) => {
        const head = [];
        if (b > 0 && meters.has(b)) head.push(`\\ts (${meters.get(b).num} ${meters.get(b).den})`);
        if (ti === 0 && vi === 0) {
          if (tempos.has(b)) head.push(`\\tempo (${Math.round(tempos.get(b))})`);
          if (sections.has(b)) head.push(`\\section (${q(sections.get(b))})`);
        }
        const bs = barStart(song, b);
        let pos = bs;
        const beats = items.map((it) => {
          const start = pos;
          pos += it.ticks;
          const txt = beatText(it, track, key, {
            chord: ti === chordTrack && vi === 0 ? chordStarts.get(start) : undefined,
          });
          // durations as a ":N" prefix only when they change (a ".N" suffix would read "42.8" as fret.string)
          const prefix = it.den !== curDen ? `:${it.den} ` : '';
          curDen = it.den;
          return prefix + txt;
        });
        lines.push((head.length ? head.join(' ') + ' ' : '') + beats.join(' ') + (b < bars.length - 1 ? ' |' : ''));
      });
    });
    lines.push('');
  });
  void meterAt;
  return lines.join('\n');
}

function avgPitch(track) {
  if (!track.notes.length) return 60;
  return track.notes.reduce((a, n) => a + n.pitch, 0) / track.notes.length;
}

function beatText(it, track, key, { chord }) {
  const dur = '';
  const beatFx = [];
  if (it.dots) beatFx.push('d');
  if (it.tu) beatFx.push(`tu (${it.tu.n} ${it.tu.m})`);
  if (it.kind === 'note' && it.first) {
    const lyric = it.notes.find((n) => n.lyric)?.lyric;
    if (lyric) beatFx.push(`lyrics ${q(lyric)}`);
  }
  if (chord) beatFx.push(`ch ${q(chord)}`);
  const bfx = beatFx.length ? `{${beatFx.join(' ')}}` : '';
  if (it.kind === 'rest') return `r${dur}${bfx}`;
  const parts = it.notes.map((n) => {
    let v;
    if (track.kind === 'fretted') v = `${n.fret}.${n.string}`;
    else if (track.kind === 'drums') v = `${n.pitch}`;
    else v = spellNameInKey(n.pitch, key);
    const fx = it.tieIn ? ['t'] : it.first ? noteFx(n) : [];
    if (it.tieIn && track.kind === 'drums') return null; // drums don't tie
    return v + (fx.length ? `{${fx.join(' ')}}` : '');
  }).filter(Boolean);
  if (!parts.length) return `r${dur}${bfx}`;
  const body = parts.length === 1 ? parts[0] : `(${parts.join(' ')})`;
  return `${body}${dur}${bfx}`;
}
